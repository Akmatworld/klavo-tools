/**
 * @file Userscripts from https://github.com/voidmain02/KgScripts.
 *
 * MV3 forbids executing remotely hosted code with eval(), so two modes are used:
 *
 *  - "remote": the `userScripts` API is available (Chrome: the "Allow User Scripts"
 *    toggle on the extension details page; Firefox: the optional `userScripts`
 *    permission). Scripts are downloaded from the KgScripts repository and kept
 *    up to date, like in the original KlavoTools.
 *
 *  - "bundled": the `userScripts` API is not available. A snapshot of KgScripts,
 *    packaged with the extension at build time, is registered with
 *    `chrome.scripting.registerContentScripts`. Only the scripts present in the
 *    snapshot are available, without updates.
 *
 * In the "remote" mode scripts run in the isolated USER_SCRIPT world (like the
 * original content-script eval), with a CSP that allows inline scripts. In the
 * "bundled" mode they run in the page (MAIN) world, because the isolated world of
 * MV3 content scripts forbids inserting inline <script> elements.
 */
import { storage } from './storage.js';
import { request } from './http.js';
import { normalizeConfigEntry, parseMetadata, wrapUserscript } from '../shared/userscript.js';
import { SITE_MATCHES, USERJS_CONFIG_URL, USERJS_DIRECTORY_URL } from './constants.js';

const KEY_CONFIG = 'userjs_config';
const KEY_CODE = 'userjs_code';
const KEY_DISABLED = 'userjs_disabled';
const KEY_SIGNATURE = 'userjs_signature';
const ID_PREFIX = 'kts-us-';
const USER_SCRIPT_WORLD_CSP = "script-src 'self' 'unsafe-eval' 'unsafe-inline'; object-src 'self'";

/** @returns {Promise.<boolean>} */
export async function isUserScriptsApiAvailable() {
    try {
        // Throws (or chrome.userScripts is undefined) when the API is not allowed:
        await chrome.userScripts.getScripts();
        return true;
    } catch (error) {
        return false;
    }
}

export class UserJS {
    constructor() {
        this._bundled = null;
        this._queue = Promise.resolve();
        this._mode = null;
    }

    /** Loads the bundled snapshot index (generated by the build script). */
    async _getBundled() {
        if (!this._bundled) {
            try {
                const response = await fetch(chrome.runtime.getURL('/userscripts/index.json'));
                const list = await response.json();
                this._bundled = {};
                for (const entry of list) {
                    this._bundled[entry.name] = entry;
                }
            } catch (error) {
                console.error('KlavoTools: bundled userscripts index not found', error);
                this._bundled = {};
            }
        }
        return this._bundled;
    }

    async _getConfig() {
        const config = storage.getItem(KEY_CONFIG);
        if (config && Object.keys(config).length) {
            return config;
        }
        const bundled = await this._getBundled();
        const result = {};
        for (const name in bundled) {
            result[name] = normalizeConfigEntry(bundled[name]);
        }
        return result;
    }

    _isDisabled(name, entry) {
        const overrides = storage.getItem(KEY_DISABLED) || {};
        return typeof overrides[name] === 'boolean' ? overrides[name] : !!entry.disabled;
    }

    /** Runs tasks one by one, so registrations never interleave. */
    _enqueue(task) {
        const result = this._queue.then(task);
        this._queue = result.catch((error) => {
            console.error('KlavoTools: userscripts task failed', error);
        });
        return result;
    }

    /**
     * Returns all known userscripts for the options page (without the source code).
     * @returns {Promise.<Object.<string, Object>>}
     */
    async getAllScripts() {
        const config = await this._getConfig();
        const bundled = await this._getBundled();
        const remote = await isUserScriptsApiAvailable();
        const result = {};
        for (const name in config) {
            const entry = config[name];
            result[name] = Object.assign({}, entry, {
                disabled: this._isDisabled(name, entry),
                // Whether the script can work in the current mode:
                available: remote || !!bundled[name],
            });
        }
        return result;
    }

    async getStatus() {
        const remote = await isUserScriptsApiAvailable();
        return {
            mode: remote ? 'remote' : 'bundled',
            userScriptsApi: remote,
            userScriptsPermissionOptional: !!(chrome.runtime.getManifest().optional_permissions || [])
                .includes('userScripts'),
        };
    }

    /**
     * @param {string} name
     * @param {{disabled: boolean}} data
     */
    async updateScriptData(name, data) {
        const config = await this._getConfig();
        if (!config[name]) {
            throw new Error('Userscript ' + name + ' not found');
        }
        if (data && typeof data.disabled === 'boolean') {
            const overrides = storage.getItem(KEY_DISABLED) || {};
            overrides[name] = data.disabled;
            await storage.setItem(KEY_DISABLED, overrides);
        }
        return this.apply();
    }

    /**
     * Downloads the latest config and updated scripts (only when the userScripts API
     * is available, since remote code can't be executed otherwise), then re-applies
     * registrations.
     */
    sync() {
        return this._enqueue(async () => {
            let remoteConfig;
            try {
                const list = await request({
                    url: USERJS_CONFIG_URL,
                    contentType: 'json',
                    credentials: 'omit',
                });
                if (!Array.isArray(list)) {
                    throw new Error('Got bad userscripts configuration');
                }
                remoteConfig = {};
                for (const entry of list) {
                    remoteConfig[entry.name] = normalizeConfigEntry(entry);
                }
            } catch (error) {
                console.log('KlavoTools: error while loading userscripts config: ' + error);
            }

            if (remoteConfig && await isUserScriptsApiAvailable()) {
                const codes = storage.getItem(KEY_CODE) || {};
                for (const name of Object.keys(codes)) {
                    if (!remoteConfig[name]) {
                        delete codes[name];
                    }
                }
                for (const name in remoteConfig) {
                    const entry = remoteConfig[name];
                    if (codes[name] && codes[name].version === entry.version) {
                        continue;
                    }
                    try {
                        const code = await request({
                            url: USERJS_DIRECTORY_URL + '/' + encodeURIComponent(name) + '.user.js',
                            credentials: 'omit',
                        });
                        codes[name] = { version: entry.version, code };
                    } catch (error) {
                        console.log('KlavoTools: failed to download userscript ' + name + ': ' + error);
                    }
                }
                await storage.setItem(KEY_CODE, codes);
            }

            if (remoteConfig) {
                await storage.setItem(KEY_CONFIG, remoteConfig);
            }
            return this._apply(true);
        });
    }

    /** Re-applies registrations if the mode or the set of enabled scripts changed. */
    apply(force = false) {
        return this._enqueue(() => this._apply(force));
    }

    async _apply(force) {
        const remote = await isUserScriptsApiAvailable();
        const config = await this._getConfig();
        const enabled = Object.keys(config).filter((name) => {
            const entry = config[name];
            return !entry.broken && !this._isDisabled(name, entry);
        });

        const codes = storage.getItem(KEY_CODE) || {};
        const signature = JSON.stringify({
            // Re-register after extension updates (registration options may change):
            extension: chrome.runtime.getManifest().version,
            remote,
            scripts: enabled.map((name) => [name, remote && codes[name] ? codes[name].version : 'bundled']),
        });
        if (!force && signature === storage.getItem(KEY_SIGNATURE) && await this._isRegistered(remote, enabled)) {
            return;
        }

        if (remote) {
            await this._registerRemote(enabled, config, codes);
        } else {
            await this._registerBundled(enabled);
        }
        this._mode = remote ? 'remote' : 'bundled';
        await storage.setItem(KEY_SIGNATURE, signature);
    }

    async _isRegistered(remote, enabled) {
        try {
            const registered = remote
                ? await chrome.userScripts.getScripts()
                : await chrome.scripting.getRegisteredContentScripts();
            const ids = new Set(registered.map((script) => script.id).filter((id) => id.startsWith(ID_PREFIX)));
            if (!remote) {
                const bundled = await this._getBundled();
                enabled = enabled.filter((name) => bundled[name]);
            }
            return ids.size === enabled.length && enabled.every((name) => ids.has(ID_PREFIX + name));
        } catch (error) {
            return false;
        }
    }

    async _unregisterBundled() {
        const registered = await chrome.scripting.getRegisteredContentScripts();
        const ids = registered.map((script) => script.id).filter((id) => id.startsWith(ID_PREFIX));
        if (ids.length) {
            await chrome.scripting.unregisterContentScripts({ ids });
        }
    }

    async _registerBundled(enabled) {
        const bundled = await this._getBundled();
        await this._unregisterBundled();
        const scripts = enabled.filter((name) => bundled[name]).map((name) => ({
            id: ID_PREFIX + name,
            matches: SITE_MATCHES,
            js: [bundled[name].file],
            runAt: bundled[name].runAt,
            // The isolated world of MV3 content scripts has the extension CSP, which
            // blocks inline <script> elements most of KgScripts inject. The scripts are
            // written for `@grant none` (page context), so run them in the page world:
            world: 'MAIN',
            persistAcrossSessions: true,
        }));
        if (scripts.length) {
            await chrome.scripting.registerContentScripts(scripts);
        }
    }

    async _registerRemote(enabled, config, codes) {
        // Remove the bundled registrations, if any (the API mode has priority):
        await this._unregisterBundled().catch(() => {});

        try {
            await chrome.userScripts.configureWorld({ csp: USER_SCRIPT_WORLD_CSP, messaging: false });
        } catch (error) {
            console.log('KlavoTools: userScripts.configureWorld failed: ' + error);
        }

        const bundled = await this._getBundled();
        const scripts = [];
        for (const name of enabled) {
            let code = codes[name] && codes[name].code;
            if (!code && bundled[name]) {
                // Not downloaded yet: use the bundled snapshot as a fallback.
                code = await fetch(chrome.runtime.getURL(bundled[name].raw)).then((r) => r.text()).catch(() => null);
            }
            if (!code) {
                continue;
            }
            const meta = parseMetadata(code);
            scripts.push({
                id: ID_PREFIX + name,
                matches: SITE_MATCHES,
                js: [{ code: wrapUserscript(name, code, meta) }],
                runAt: meta.runAt,
                world: 'USER_SCRIPT',
            });
        }

        await chrome.userScripts.unregister();
        if (scripts.length) {
            await chrome.userScripts.register(scripts);
        }
    }
}
